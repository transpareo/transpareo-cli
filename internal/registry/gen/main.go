// Command gen writes registry.gen.go from the embedded
// specification: one Go literal per operation, so the binary
// carries its operation table without parsing the document at
// start.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os"
	"strconv"
	"strings"

	"github.com/transpareo/transpareo-cli/internal/registry"
	"github.com/transpareo/transpareo-cli/spec"
)

func main() {
	reg, err := registry.Load(spec.JSON)
	if err != nil {
		log.Fatal(err)
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/registry/gen from "+
		"spec/openapi.json; DO NOT EDIT.\n\npackage registry\n\n"+
		"import \"encoding/json\"\n\n")
	fmt.Fprintf(&b, "const generatedVersion = %s\n\n", strconv.Quote(reg.Version))
	fmt.Fprintf(&b, "var generatedOperations = []Operation{\n")
	for _, op := range reg.Operations {
		writeOperation(&b, op)
	}
	fmt.Fprintf(&b, "}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("formatting: %v\n%s", err, b.Bytes())
	}
	if err := os.WriteFile("registry.gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func writeOperation(b *bytes.Buffer, op registry.Operation) {
	fmt.Fprintf(b, "\t{\n")
	str := func(name, value string) {
		if value != "" {
			fmt.Fprintf(b, "\t\t%s: %s,\n", name, strconv.Quote(value))
		}
	}
	boolean := func(name string, value bool) {
		if value {
			fmt.Fprintf(b, "\t\t%s: true,\n", name)
		}
	}
	raw := func(name string, value json.RawMessage) {
		if len(value) > 0 {
			fmt.Fprintf(b, "\t\t%s: json.RawMessage(%s),\n", name, rawLiteral(value))
		}
	}
	str("ID", op.ID)
	str("Group", op.Group)
	str("Tag", op.Tag)
	str("Method", op.Method)
	str("Path", op.Path)
	str("Summary", op.Summary)
	str("Description", op.Description)
	writeParams(b, "PathParams", op.PathParams)
	writeParams(b, "QueryParams", op.QueryParams)
	writeParams(b, "HeaderParams", op.HeaderParams)
	writeBodies(b, op.RequestBodies)
	boolean("RequestRequired", op.RequestRequired)
	str("ResponseStatus", op.ResponseStatus)
	str("ResponseContentType", op.ResponseContentType)
	raw("ResponseSchema", op.ResponseSchema)
	raw("ResponseExample", op.ResponseExample)
	fmt.Fprintf(b, "\t\tPermission: %s,\n", stringSlice(op.Permission))
	boolean("Destructive", op.Destructive)
	boolean("Safe", op.Safe)
	boolean("NDJSON", op.NDJSON)
	boolean("Task", op.Task)
	boolean("Idempotent", op.Idempotent)
	fmt.Fprintf(b, "\t\tSecurity: %s,\n", stringSlice(op.Security))
	boolean("Public", op.Public)
	boolean("UserOnly", op.UserOnly)
	fmt.Fprintf(b, "\t},\n")
}

func writeBodies(b *bytes.Buffer, bodies []registry.RequestBody) {
	if len(bodies) == 0 {
		return
	}
	fmt.Fprintf(b, "\t\tRequestBodies: []RequestBody{\n")
	for _, body := range bodies {
		fmt.Fprintf(b, "\t\t\t{ContentType: %s", strconv.Quote(body.ContentType))
		if len(body.Schema) > 0 {
			fmt.Fprintf(b, ", Schema: json.RawMessage(%s)",
				rawLiteral(body.Schema))
		}
		if len(body.Example) > 0 {
			fmt.Fprintf(b, ", Example: json.RawMessage(%s)",
				rawLiteral(body.Example))
		}
		fmt.Fprintf(b, "},\n")
	}
	fmt.Fprintf(b, "\t\t},\n")
}

func writeParams(b *bytes.Buffer, name string, params []registry.Param) {
	if len(params) == 0 {
		return
	}
	fmt.Fprintf(b, "\t\t%s: []Param{\n", name)
	for _, p := range params {
		fmt.Fprintf(b, "\t\t\t{Name: %s, In: %s", strconv.Quote(p.Name),
			strconv.Quote(p.In))
		if p.Description != "" {
			fmt.Fprintf(b, ", Description: %s", strconv.Quote(p.Description))
		}
		if p.Required {
			fmt.Fprintf(b, ", Required: true")
		}
		if len(p.Schema) > 0 {
			fmt.Fprintf(b, ", Schema: json.RawMessage(%s)", rawLiteral(p.Schema))
		}
		fmt.Fprintf(b, "},\n")
	}
	fmt.Fprintf(b, "\t\t},\n")
}

// rawLiteral renders JSON as a Go string literal: a raw string
// when it holds no backtick, a quoted one otherwise.
func rawLiteral(value json.RawMessage) string {
	s := string(value)
	if !strings.Contains(s, "`") {
		return "`" + s + "`"
	}
	return strconv.Quote(s)
}

func stringSlice(values []string) string {
	if len(values) == 0 {
		return "[]string{}"
	}
	quoted := make([]string, len(values))
	for i, v := range values {
		quoted[i] = strconv.Quote(v)
	}
	return "[]string{" + strings.Join(quoted, ", ") + "}"
}
