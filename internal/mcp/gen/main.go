// Command gen writes tools.gen.go from the vendored tool
// catalogue: the curated tool table and the instructions an
// assistant reads on connect.
//
// Both servers over this API used to keep that table by hand, one
// in Ruby and one here, and a test compared them. The catalogue
// now publishes the declaration, so there is one table and this
// side derives from it. A curated tool cannot differ between the
// two any more; it is the same row read twice.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"strconv"
	"strings"

	"github.com/transpareo/transpareo-cli/spec"
)

// groups maps a catalogue group onto the constant this package
// names it with. A group missing here is a new one, and the tools
// in it would silently land in a group --tools does not offer, so
// the generator stops instead.
var groups = map[string]string{
	"identity":  "GroupIdentity",
	"discovery": "GroupDiscovery",
	"products":  "GroupProducts",
	"dpps":      "GroupDpps",
	"data":      "GroupData",
	"webhooks":  "GroupWebhooks",
	"help":      "GroupHelp",
	"tasks":     "GroupTasks",
}

// kinds maps a catalogue kind onto the constant that decides how
// arguments become a request.
var kinds = map[string]string{
	"list":  "kindList",
	"get":   "kindGet",
	"write": "kindWrite",
	"rows":  "kindRows",
}

func main() {
	doc := spec.Catalogue()
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/mcp/gen from "+
		"spec/mcp-tools.json; DO NOT EDIT.\n\npackage mcp\n\n")

	if doc.Instructions == "" {
		log.Fatal("the vendored catalogue carries no instructions")
	}
	fmt.Fprintf(&b, "// instructions is what the assistant reads when it "+
		"connects.\nconst instructions = %s\n\n", literal(doc.Instructions))

	fmt.Fprintf(&b, "// curated is the tool table, one entry per tool the "+
		"catalogue\n// declares over an operation. Every other operation "+
		"of the\n// registry is in viaCallAPIOnly, hidden from consumers, "+
		"or a\n// user-only operation; a test enforces it.\n")
	fmt.Fprintf(&b, "var curated = []Tool{\n")
	for _, name := range doc.CuratedNames() {
		writeTool(&b, doc.Tools[name])
	}
	fmt.Fprintf(&b, "}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("formatting: %v\n%s", err, b.Bytes())
	}
	if err := os.WriteFile("tools.gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func writeTool(b *bytes.Buffer, tool spec.CatalogueTool) {
	group, ok := groups[tool.Group]
	if !ok {
		log.Fatalf("%s is in group %q, which this package does not name",
			tool.Name, tool.Group)
	}
	kind, ok := kinds[tool.Kind]
	if !ok {
		log.Fatalf("%s is of kind %q, which this package cannot build a "+
			"request from", tool.Name, tool.Kind)
	}
	fmt.Fprintf(b, "\t{\n\t\tName: %s,\n\t\tGroup: %s,\n\t\tOperation: %s,"+
		"\n\t\tKind: %s,\n", strconv.Quote(tool.Name), group,
		strconv.Quote(tool.Operation), kind)
	if tool.Confirm != "" {
		fmt.Fprintf(b, "\t\tConfirm: %s,\n", strconv.Quote(tool.Confirm))
	}
	if tool.Sentence != "" {
		fmt.Fprintf(b, "\t\tDescription: %s,\n", literal(tool.Sentence))
	}
	fmt.Fprintf(b, "\t},\n")
}

// literal renders a string as a raw Go literal when it holds no
// backtick, so a sentence stays readable in the generated file.
func literal(s string) string {
	if !strings.Contains(s, "`") {
		return "`" + s + "`"
	}
	return strconv.Quote(s)
}
